package com.xceptance.xcmailr.config;

import java.time.Year;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.info.BuildProperties;
import org.springframework.stereotype.Component;
import org.springframework.web.bind.annotation.ControllerAdvice;
import org.springframework.web.bind.annotation.ModelAttribute;

/**
 * Global controller advice providing common application metadata such as copyright year range
 * and application version as model attributes across all web console views.
 *
 * @author Xceptance Software Technologies GmbH
 */
@Component
@ControllerAdvice
public class AppInfoAdvice
{
    /**
     * Inception year of the XCMailr project.
     */
    public static final int INCEPTION_YEAR = 2013;

    /**
     * Fallback application version string if build-info metadata is absent.
     */
    public static final String DEFAULT_VERSION = "4.0.0";

    private final String appVersion;

    /**
     * Constructs a new {@link AppInfoAdvice} with optional {@link BuildProperties} and configured fallback version.
     *
     * @param buildProperties          optional build metadata generated by the Spring Boot Maven plugin
     * @param configuredDefaultVersion application version configured via properties or defaulting to {@value #DEFAULT_VERSION}
     */
    public AppInfoAdvice(@Autowired(required = false) final BuildProperties buildProperties,
                         @Value("${xcmailr.app.version:4.0.0}") final String configuredDefaultVersion)
    {
        this.appVersion = resolveVersion(buildProperties, configuredDefaultVersion);
    }

    /**
     * Resolves the active application version prioritizing {@link BuildProperties}, then configured default version,
     * then package implementation version, and finally {@value #DEFAULT_VERSION}.
     *
     * @param buildProperties          optional Spring Boot build properties
     * @param configuredDefaultVersion fallback property value
     * @return resolved non-blank version string
     */
    private String resolveVersion(final BuildProperties buildProperties, final String configuredDefaultVersion)
    {
        if (buildProperties != null && buildProperties.getVersion() != null && !buildProperties.getVersion().isBlank())
        {
            return buildProperties.getVersion();
        }

        if (configuredDefaultVersion != null && !configuredDefaultVersion.isBlank())
        {
            return configuredDefaultVersion;
        }

        final String packageVersion = getClass().getPackage().getImplementationVersion();
        if (packageVersion != null && !packageVersion.isBlank())
        {
            return packageVersion;
        }

        return DEFAULT_VERSION;
    }

    /**
     * Returns the dynamic copyright year range formatted as {@code 2013-YYYY} where {@code YYYY}
     * reflects the current calendar year.
     *
     * @return formatted copyright year range (e.g. {@code "2013-2026"})
     */
    @ModelAttribute("copyrightYear")
    public String getCopyrightYear()
    {
        final int currentYear = Year.now().getValue();
        return String.format("%d-%d", INCEPTION_YEAR, currentYear);
    }

    /**
     * Returns the resolved application version string.
     *
     * @return active application version
     */
    @ModelAttribute("appVersion")
    public String getAppVersion()
    {
        return appVersion;
    }
}
